export function getKwNumericValue(cap) {
  if (!cap) return 9999
  const kwStr = String(cap.kw || cap.id || cap.slug || '')
  const match = kwStr.match(/(\d+(?:\.\d+)?)/)
  if (match) return parseFloat(match[1])
  return Number(cap.order ?? 999)
}

export function sortCapacitiesAscending(list) {
  return [...(list || [])].sort((a, b) => {
    const valA = getKwNumericValue(a)
    const valB = getKwNumericValue(b)
    if (valA !== valB) return valA - valB
    return (a.order ?? 999) - (b.order ?? 999)
  })
}

export function getCapacityBySlug(slug) {
  if (!slug) return null
  const clean = slug.toLowerCase().trim()
  return SOLAR_CAPACITIES_DATA.find(
    (c) => c.id === clean || c.slug === clean || (c.aliases && c.aliases.includes(clean))
  ) || null
}
